"""Draw the original fox tray icon using only Python's standard library."""

from pathlib import Path
from base64 import b64encode
from struct import pack
from zlib import compress, crc32

SIZE = 64
SCALE = 4
PIXELS = [[None for _ in range(SIZE * SCALE)] for _ in range(SIZE * SCALE)]


def polygon(points, color):
    scaled = [(x * SCALE, y * SCALE) for x, y in points]
    for y in range(SIZE * SCALE):
        py = y + 0.5
        for x in range(SIZE * SCALE):
            px = x + 0.5
            inside = False
            previous = scaled[-1]
            for current in scaled:
                if (current[1] > py) != (previous[1] > py):
                    edge_x = current[0] + (py - current[1]) * (previous[0] - current[0]) / (previous[1] - current[1])
                    if px < edge_x:
                        inside = not inside
                previous = current
            if inside:
                PIXELS[y][x] = color


def ellipse(cx, cy, rx, ry, color):
    for y in range(max(0, int((cy - ry) * SCALE)), min(SIZE * SCALE, int((cy + ry) * SCALE) + 1)):
        for x in range(max(0, int((cx - rx) * SCALE)), min(SIZE * SCALE, int((cx + rx) * SCALE) + 1)):
            if ((x + 0.5) / SCALE - cx) ** 2 / rx ** 2 + ((y + 0.5) / SCALE - cy) ** 2 / ry ** 2 <= 1:
                PIXELS[y][x] = color


OUTLINE = (65, 38, 31)
ORANGE = (241, 130, 55)
CREAM = (255, 234, 195)
BLACK = (43, 37, 39)

polygon([(10, 27), (15, 4), (31, 17)], OUTLINE)
polygon([(54, 27), (49, 4), (33, 17)], OUTLINE)
polygon([(15, 21), (18, 10), (27, 20)], ORANGE)
polygon([(49, 21), (46, 10), (37, 20)], ORANGE)
ellipse(32, 34, 27, 25, OUTLINE)
ellipse(32, 33, 25, 23, ORANGE)
ellipse(23, 43, 15, 11, CREAM)
ellipse(41, 43, 15, 11, CREAM)
ellipse(24, 32, 3, 4, BLACK)
ellipse(40, 32, 3, 4, BLACK)
polygon([(26, 43), (38, 43), (32, 49)], BLACK)


def chunk(name, data):
    return pack('!I', len(data)) + name + data + pack('!I', crc32(name + data) & 0xFFFFFFFF)


rows = bytearray()
for y in range(SIZE):
    rows.append(0)
    for x in range(SIZE):
        samples = [PIXELS[y * SCALE + dy][x * SCALE + dx] for dy in range(SCALE) for dx in range(SCALE)]
        visible = [sample for sample in samples if sample is not None]
        if visible:
            rows.extend((*[round(sum(sample[channel] for sample in visible) / len(visible)) for channel in range(3)],
                         round(255 * len(visible) / len(samples))))
        else:
            rows.extend((0, 0, 0, 0))

png = b'\x89PNG\r\n\x1a\n'
png += chunk(b'IHDR', pack('!2I5B', SIZE, SIZE, 8, 6, 0, 0, 0))
png += chunk(b'IDAT', compress(bytes(rows), 9))
png += chunk(b'IEND', b'')
Path(__file__).with_name('mascot-tray.png').write_bytes(png)
source = Path(__file__).parents[2] / 'src' / 'mascot-tray-icon.ts'
source.write_text(
    '// Original tray icon generated by assets/tray/generate-icon.py.\n'
    f"export const MASCOT_TRAY_ICON_DATA_URL = 'data:image/png;base64,{b64encode(png).decode('ascii')}';\n",
    encoding='utf-8',
)
